#!/bin/bash
# Real-kernel check of the bandwidth limits, no hardware needed: a private network namespace (unprivileged) with a
# fake LAN client and WAN host, the real vendo5 nft ruleset, and the shaper. Prints a 3 MB download unlimited, then
# with an 8 Mbit/s (1 MB/s) limit, and the byte counters.   Run: unshare -Urn bash scripts/shaper-netns-test.sh
set -e
trap 'kill ${CP:-} ${WP:-} $(jobs -p) 2>/dev/null; true' EXIT
R=$(cd "$(dirname "$0")/.." && pwd); J=$(mktemp -d)
ip link set lo up
unshare -n sleep 600 >/dev/null 2>&1 & CP=$!
unshare -n sleep 600 >/dev/null 2>&1 & WP=$!
sleep 0.5
ip link add br-lan type veth peer name c0; ip link set c0 netns $CP
ip link add eth0 type veth peer name w0; ip link set w0 netns $WP
ip addr add 10.0.0.1/19 dev br-lan; ip link set br-lan up
ip addr add 10.9.0.1/24 dev eth0; ip link set eth0 up
nsenter -t $CP -n sh -c "ip link set c0 address aa:bb:cc:dd:ee:01; ip addr add 10.0.0.5/19 dev c0; ip link set c0 up; ip link set lo up; ip route add default via 10.0.0.1"
nsenter -t $WP -n sh -c "ip addr add 10.9.0.2/24 dev w0; ip link set w0 up; ip link set lo up; ip route add default via 10.9.0.1"
sysctl -qw net.ipv4.ip_forward=1
# Reproduce the second forward base chain generated by OpenWrt fw4.
# Its effective LAN->WAN verdict follows the shipped UCI config; the MAC
# gate in the separate vendo5 table must still enforce unpaid/revoked clients.
python3 - "$R/etc-overlay/etc/config/firewall" "$J/fw4.nft" <<'FW4'
import sys,re,pathlib
config=pathlib.Path(sys.argv[1]).read_text()
blocks=re.split(r'^config ', config, flags=re.M)
defaults=next(b for b in blocks if b.startswith('defaults'))
policy=re.search(r"option forward '([^']+)'",defaults)[1].lower()
allow=any(b.startswith('forwarding') and "option src 'lan'" in b and "option dest 'wan'" in b for b in blocks)
rules='ct state established,related accept;'
if allow: rules+=' iifname "br-lan" oifname "eth0" accept;'
pathlib.Path(sys.argv[2]).write_text('table inet fw4 { chain forward { type filter hook forward priority filter; policy '+policy+'; '+rules+' }\n}\n')
FW4
nft -f "$J/fw4.nft"
nft -f $R/etc-overlay/etc/vendo5-firewall.nft
# An unpaid client's plain HTTP to ANY site must land on the port-80 portal front door, and HTTPS must be dropped.
mkdir -p $J/portal && echo PORTAL > $J/portal/index.html
(cd $J/portal && python3 -m http.server 80 --bind 10.0.0.1 >/dev/null 2>&1 &); sleep 1
nsenter -t $CP -n python3 - <<'UNPAID'
import urllib.request,socket
assert b'PORTAL' in urllib.request.urlopen('http://10.9.0.2:80/',timeout=5).read(), 'unpaid HTTP not redirected to the portal'
s=socket.socket();s.settimeout(3)
try: s.connect(('10.9.0.2',443)); raise SystemExit('FAIL: unpaid HTTPS got through')
except OSError: print('PASS: unpaid HTTP -> portal, HTTPS dropped')
UNPAID
nft add element inet vendo5 allowed '{ aa:bb:cc:dd:ee:01 }'
head -c 3000000 /dev/zero > $J/blob
(cd $J && nsenter -t $WP -n python3 -m http.server 8088 >/dev/null 2>&1 &) ; sleep 1
ping -c1 -W1 10.0.0.5 >/dev/null || true
echo "--- no limit"
nsenter -t $CP -n python3 - <<PY
import time,urllib.request
t=time.time(); n=len(urllib.request.urlopen('http://10.9.0.2:8088/blob',timeout=30).read()); print('download', n, 'bytes in %.1fs'%(time.time()-t))
PY
# An already-established TCP flow must stop when its MAC is revoked.
nsenter -t $WP -n python3 -u - <<'SERVER' >/dev/null 2>&1 &
import socket
s=socket.socket();s.setsockopt(socket.SOL_SOCKET,socket.SO_REUSEADDR,1);s.bind(('10.9.0.2',9999));s.listen()
c,_=s.accept()
while True:
 data=c.recv(1024)
 if not data:break
 c.sendall(data)
SERVER
sleep 0.5
ROUTER_PID=$$
nsenter -t $CP -n python3 - "$ROUTER_PID" <<'ESTABLISHED'
import socket,subprocess,sys
s=socket.create_connection(('10.9.0.2',9999),timeout=2)
s.sendall(b'before');assert s.recv(1024)==b'before'
subprocess.run(['nsenter','-t',sys.argv[1],'-n','nft','delete','element','inet','vendo5','allowed','{ aa:bb:cc:dd:ee:01 }'],check=True)
s.sendall(b'after')
try:
 data=s.recv(1024)
 assert not data, 'FAIL: revoked client still uses an established TCP connection'
except socket.timeout:
 print('PASS: revocation also blocks established TCP traffic')
finally:
 s.close()
 subprocess.run(['nsenter','-t',sys.argv[1],'-n','nft','add','element','inet','vendo5','allowed','{ aa:bb:cc:dd:ee:01 }'],check=True)
ESTABLISHED

echo "--- with 8M download limit (1,000,000 B/s)"
node -e "
const {execFileSync}=require('child_process');const {createShaper}=require('$R/lib/system/shaper');
const A='aa:bb:cc:dd:ee:01';const sess={[A]:{expiresAt:Date.now()+9e5,upload:'8M',download:'8M',max_data_limit:'1M'}};
global.sh=createShaper({runCommand:(a)=>execFileSync(a[0],a.slice(1),{encoding:'utf8'}),sessions:{all:()=>sess,getSession:(m)=>sess[m]},arp:{neighbors:()=>({[A]:{ip:'10.0.0.5'}})},file:'$J/e2e-limits.nft',onCap:(m)=>console.log('CAP reached for',m)});
sh.tick();
"
nsenter -t $CP -n python3 - <<PY
import time,urllib.request
t=time.time(); n=len(urllib.request.urlopen('http://10.9.0.2:8088/blob',timeout=60).read()); print('download', n, 'bytes in %.1fs'%(time.time()-t))
PY
echo "--- after revoke (not allowed): the same download must fail"
nft delete element inet vendo5 allowed '{ aa:bb:cc:dd:ee:01 }'
nsenter -t $CP -n python3 - <<PY
import urllib.request
try:
    urllib.request.urlopen('http://10.9.0.2:8088/blob', timeout=3).read(); print('FAIL: revoked client still got through')
except Exception as e:
    print('PASS: revoked client blocked (%s)' % type(e).__name__)
PY
nft list chain inet vendo5 bwlimit | grep -o 'comment.*\|bytes [0-9]*' | head -6
